const mongoose = require('mongoose');

const INSIGHT_TYPES = ['MeetingBrief', 'ConversationSummary', 'LeadIntelligence'];
const REFERENCE_TYPES = ['Meeting', 'Lead'];

const aiInsightSchema = new mongoose.Schema(
  {
    type: {
      type: String,
      required: [true, 'Insight type is required'],
      enum: { values: INSIGHT_TYPES, message: 'Invalid insight type' },
    },
    referenceType: {
      type: String,
      required: [true, 'Reference type is required'],
      enum: { values: REFERENCE_TYPES, message: 'Invalid reference type' },
    },
    referenceId: {
      type: mongoose.Schema.Types.ObjectId,
      required: [true, 'Reference ID is required'],
      index: true,
    },
    generatedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: [true, 'Generated by user is required'],
    },
    generatedAt: {
      type: Date,
      default: Date.now,
    },
    promptVersion: {
      type: String,
      required: [true, 'Prompt version is required'],
    },
    contextVersion: {
      type: String,
      required: [true, 'Context version is required'],
    },
    response: {
      type: mongoose.Schema.Types.Mixed,
      required: [true, 'AI response is required'],
    },
    metadata: {
      type: mongoose.Schema.Types.Mixed,
      default: {},
    },
  },
  { timestamps: true }
);

// Newest-first history lookups are the primary access pattern.
aiInsightSchema.index({ referenceType: 1, referenceId: 1, type: 1, generatedAt: -1 });

module.exports = mongoose.model('AIInsight', aiInsightSchema);
module.exports.INSIGHT_TYPES = INSIGHT_TYPES;
module.exports.REFERENCE_TYPES = REFERENCE_TYPES;
